#!/usr/bin/env python3
"""mod-wow-fates — writes what the client's map code needs, read from the game:

  data/lua/WowFates/WowFates_Bounds_Client.lua
      each world map's edges in world coordinates, from WorldMapArea.dbc, by the
      number GetCurrentMapAreaID returns (the WorldMapArea ID + 1, as
      mod-forever-ui's tools/map_sizes.py found): the client turns the
      Expeditions' world positions into map fractions with them.

  data/art/Interface/WowFates/Area.blp
      the area of an Expedition: the world map's quest area (WorldMapBlobFrame,
      UI-QuestBlob-Inside and UI-QuestBlob-Outside at fill alpha 128 and border
      alpha 192) drawn as a disc, its blue turned orange (red and blue swapped).

  data/art/Interface/WowFates/Tracker.blp
      the tracker's block, the modern client's Mythic+ block cut out of its
      sheets (ChallengeMode-Timer, -TimerBG-back, -TimerBG, -TimerFill from
      interface/challenges/challengemodehud.blp; bonusobjectives-bar-frame-5
      from interface/questframe/bonusobjectives.blp), the timer's blue bar and
      fill turned orange. The sheets come as PNG from the wow.export bridge
      (http://127.0.0.1:9455, as mod-forever-ui's tools/add_sheets.py), into
      the folder given by --sheets; without it, Tracker.blp is left as it is.

Usage: python tools/gen_client_data.py [game folder] [--sheets folder]
"""
import math
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "..", "installer"))
sys.path.insert(0, os.path.join(ROOT, "..", "mod-forever-ui", "tools"))
import mpq_archive  # noqa: E402
from foreverui import blp  # noqa: E402

ARGS = [a for a in sys.argv[1:] if not a.startswith("--")]
SHEETS = sys.argv[sys.argv.index("--sheets") + 1] if "--sheets" in sys.argv else None
if SHEETS in ARGS:
    ARGS.remove(SHEETS)
GAME = ARGS[0] if ARGS else r"E:\world of warcraft 3.3.5a hd"

# The tracker's pieces: name -> (sheet, left, top, width, height, recolour) in the modern
# client, and where they go in Tracker.blp (left, top). Mirrored in WowFates_Client.lua.
TRACKER_SIZE = (512, 256)
TRACKER_PIECES = {
    "timer":      ("interface/challenges/challengemodehud.png", 621, 113, 261, 87, False, (0, 0)),
    "timerBack":  ("interface/challenges/challengemodehud.png", 649, 94, 223, 11, False, (0, 88)),
    "timerBG":    ("interface/challenges/challengemodehud.png", 649, 81, 223, 11, True, (0, 100)),
    "timerFill":  ("interface/challenges/challengemodehud.png", 621, 202, 223, 11, True, (0, 112)),
    "barFrame":   ("interface/questframe/bonusobjectives.png", 1, 315, 240, 51, False, (0, 124)),
}

ARCHIVES = ["enus/patch-enus-3.mpq", "enus/patch-enus-2.mpq", "enus/patch-enus.mpq",
            "enus/locale-enus.mpq", "frfr/patch-frfr-3.mpq", "frfr/patch-frfr-2.mpq",
            "frfr/patch-frfr.mpq", "frfr/locale-frfr.mpq", "patch-3.mpq", "patch-2.mpq",
            "patch.mpq", "lichking.mpq", "expansion.mpq", "common-2.mpq", "common.mpq"]

# The continents an Expedition may be on
CONTINENTS = (0, 1, 530, 571)

# The quest area's colours and alphas (UI-QuestBlob-*, WorldMapBlobFrame_OnLoad), red and blue
# swapped
FILL = (255, 109, 58)
BORDER = (255, 187, 104)
FILL_ALPHA = 128 / 255
BORDER_ALPHA = 192 / 255
# UI-QuestBlob-Outside's alpha, from the edge inward (its 16 rows, the last ones 0)
BORDER_PROFILE = [220, 198, 155, 113, 82, 53, 34, 16, 5, 0]
SIZE = 256
BAND = 0.16           # the border's width, a share of the radius


def read_dbc(name):
    for rel in ARCHIVES:
        path = os.path.join(GAME, "Data", rel)
        if not os.path.exists(path):
            continue
        archive = mpq_archive.Archive(path)
        if archive.contains("DBFilesClient\\" + name):
            raw = archive.read("DBFilesClient\\" + name)
            count, fields, size, _ = struct.unpack("<4I", raw[4:20])
            return [raw[20 + i * size:20 + (i + 1) * size] for i in range(count)], fields
    raise SystemExit("%s not found" % name)


def bounds():
    rows, fields = read_dbc("WorldMapArea.dbc")
    assert fields == 11, fields
    out = []
    for r in rows:
        ident, map_id = struct.unpack_from("<2I", r, 0)
        left, right, top, bottom = struct.unpack_from("<4f", r, 16)
        if map_id in CONTINENTS and left != right and top != bottom:
            out.append((ident + 1, map_id, left, right, top, bottom))
    out.sort()
    lines = [
        "--[[ mod-wow-fates — each world map's edges in world coordinates, by",
        "     GetCurrentMapAreaID: { map, left, right, top, bottom }. Generated by",
        "     tools/gen_client_data.py from WorldMapArea.dbc. Client side, shipped by AIO. ]]",
        "",
        "local AIO = AIO or require(\"AIO\")",
        "",
        "if AIO.AddAddon() then",
        "    return",
        "end",
        "",
        "WowFatesBounds = {",
    ]
    for ident, map_id, left, right, top, bottom in out:
        lines.append("    [%d] = { %d, %.1f, %.1f, %.1f, %.1f }," % (ident, map_id, left, right, top, bottom))
    lines.append("}")
    path = os.path.join(ROOT, "data", "lua", "WowFates", "WowFates_Bounds_Client.lua")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d maps" % len(out))


def profile(t):
    # t: 0 at the edge, 1 at the inner end of the border
    x = t * (len(BORDER_PROFILE) - 1)
    i = min(int(x), len(BORDER_PROFILE) - 2)
    f = x - i
    return (BORDER_PROFILE[i] * (1 - f) + BORDER_PROFILE[i + 1] * f) / 255


def texture():
    center = (SIZE - 1) / 2
    radius = SIZE / 2 - 1.5
    rgba = bytearray()
    for y in range(SIZE):
        for x in range(SIZE):
            d = math.hypot(x - center, y - center)
            cover = max(0.0, min(1.0, radius + 0.5 - d))
            if cover <= 0:
                rgba += bytes((FILL[0], FILL[1], FILL[2], 0))
                continue
            edge = max(0.0, (radius - d) / radius)
            b = profile(min(edge / BAND, 1.0)) * BORDER_ALPHA
            a = b + FILL_ALPHA * (1 - b)
            rgb = [(BORDER[k] * b + FILL[k] * FILL_ALPHA * (1 - b)) / a for k in range(3)]
            rgba += bytes((round(rgb[0]), round(rgb[1]), round(rgb[2]), round(a * cover * 255)))
    # Drawn far smaller than 256 on the maps: the reduced levels, each from the full image
    from PIL import Image
    image = Image.frombytes("RGBA", (SIZE, SIZE), bytes(rgba))
    mipmaps = []
    size = SIZE // 2
    while size >= 1:
        mipmaps.append((size, size, image.resize((size, size), Image.LANCZOS).tobytes()))
        size //= 2
    path = os.path.join(ROOT, "data", "art", "Interface", "WowFates", "Area.blp")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as f:
        f.write(blp.encode(SIZE, SIZE, bytes(rgba), mipmaps))


def tracker():
    from PIL import Image
    sheet = Image.new("RGBA", TRACKER_SIZE, (0, 0, 0, 0))
    sources = {}
    for name, (src, left, top, width, height, orange, at) in TRACKER_PIECES.items():
        if src not in sources:
            sources[src] = Image.open(os.path.join(SHEETS, src.replace("/", os.sep))).convert("RGBA")
        piece = sources[src].crop((left, top, left + width, top + height))
        if orange:
            r, g, b, a = piece.split()
            piece = Image.merge("RGBA", (b, g, r, a))
        sheet.paste(piece, at)
    mipmaps = []
    w, h = TRACKER_SIZE
    while w > 1 or h > 1:
        w, h = max(w // 2, 1), max(h // 2, 1)
        mipmaps.append((w, h, sheet.resize((w, h), Image.LANCZOS).tobytes()))
    path = os.path.join(ROOT, "data", "art", "Interface", "WowFates", "Tracker.blp")
    with open(path, "wb") as f:
        f.write(blp.encode(TRACKER_SIZE[0], TRACKER_SIZE[1], sheet.tobytes(), mipmaps))



if __name__ == "__main__":
    bounds()
    texture()
    if SHEETS:
        tracker()
